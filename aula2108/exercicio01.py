# 04 numeros entrados pelo usuario
n1 = float(input("Digite o primeiro numero: "))
n2 = float(input("Digite o segundo numero: "))
n3 = float(input("Digite o terceiro numero: "))
n4 = float(input("Digite o quarto numero: "))
# calcular e exibir a soma
soma = n1 + n2 + n3 + n4
print(f"A soma dos numeros é: {soma}")
# calcular e exibir a media
media = soma / 4
print(f"A media dos numeros é: {media}")
# calcular e exibir o produto dos 04 numeros
produto = n1 * n2 * n3 * n4
print(f"O produto dos numeros é: {produto}")